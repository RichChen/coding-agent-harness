# --- run discovery ---------------------------------------------------------------------------------------------

def discover() -> list[dict]:
    specs = []
    for exp, pattern, cfg_index in (("A5", "a5-main/*/*/r*", -2), ("A6-R", "a6-retry/*/*/*/r*", -3),
                                    ("CR-2", "cr2-main/*/*/r*", -2)):
        for d in sorted(RUNS.glob(pattern)):
            if not d.is_dir() or not (d / "summary.json").is_file():
                continue
            parts = d.relative_to(RUNS).parts
            specs.append(dict(experiment=exp, config=parts[cfg_index], task=parts[1], repeat=d.name,
                              run_dir=str(d), infra_retired=".infra" in d.name))
    e3 = load_json(HARNESS / "scripts/audit/errata_2026_11/e3_p4_scale54_final.json")
    roots = dict(P4_BATCHES)
    for a in e3["allocations"]:
        d = roots[a["batch"]] / "batch" / f"run-{a['run_index']:02d}-{a['condition']}"
        specs.append(dict(experiment="P4", config=a["condition"], task=a["task_id"], repeat=a["repeat"],
                          run_dir=str(d), infra_retired=False, p4_batch=a["batch"], p4_run_index=a["run_index"],
                          p4_outcome=a["outcome"]))
    specs.append(dict(experiment="P4-first", config="first", task="sphinx-8721", repeat=1,
                      run_dir=str(P4_FIRST / "solve"), infra_retired=False))
    return specs


def outcome(spec: dict) -> tuple[bool | None, str]:
    """(solved, status); status 'excluded:*' keeps the run out of the tables."""
    if spec["experiment"] == "P4":
        o = spec["p4_outcome"]
        return (o == "passed", o) if o in ("passed", "behavior_failed") else (None, "excluded:" + o)
    if spec["experiment"] == "P4-first":
        target = load_json(P4_FIRST / "target" / "result.json")
        return target.get("status") == "passed", str(target.get("status"))
    if spec["infra_retired"]:
        return None, "excluded:infra_retired"
    summary = load_json(Path(spec["run_dir"]) / "summary.json")
    if summary.get("status") == "infra_error":
        return None, "excluded:infra_error"
    return bool(summary.get("solved")), str(summary.get("status"))


# --- per run ---------------------------------------------------------------------------------------------------

def overlaps(u: Unit, p: Unit, lengths: dict[str, int]) -> bool:
    if u.kind == "search" or p.kind == "search":
        return u.kind == p.kind == "search" and u.pattern == p.pattern and u.path == p.path
    if u.path != p.path:
        return False
    if u.kind == "tail" or p.kind == "tail":
        other = p if u.kind == "tail" else u
        if other.kind == "tail":
            return True
        total = lengths.get(u.path)
        return other.end is None or (total is not None and other.end >= total)
    u_end = u.end if u.end is not None else float("inf")
    p_end = p.end if p.end is not None else float("inf")
    return u.start <= p_end and p.start <= u_end


def coverage(u: Unit, priors: list[Unit], lengths: dict[str, int]) -> float:
    if not priors:
        return 0.0
    if u.kind == "search":
        return 1.0
    total = lengths.get(u.path)
    if u.kind == "tail":
        best = 0.0
        for p in priors:
            if p.kind == "tail":
                best = max(best, min(1.0, p.n / u.n))
            elif p.start == 1 and (p.end is None or (total and p.end >= total)):
                best = 1.0
        return best
    end = u.end if u.end is not None else total
    if end is None:
        return 1.0 if any(p.kind == "lines" and p.end is None and p.start <= u.start for p in priors) else 0.0
    covered = set()
    for p in priors:
        if p.kind == "tail":
            if total is None:
                continue
            p_start, p_end = max(1, total - p.n + 1), total
        elif p.kind == "lines":
            p_start, p_end = p.start, p.end if p.end is not None else end
        else:
            continue
        covered.update(range(max(u.start, p_start), min(end, p_end) + 1))
    return len(covered) / max(1, end - u.start + 1)


def _under(path: str, root: str) -> bool:
    return root == "" or path == root or path.startswith(root.rstrip("/") + "/")


def _search_roots(u: Unit) -> list[str]:
    roots = []
    for root in u.path.split("|"):
        root = root.split("::", 1)[0]
        glob = re.search(r"[*?\[{]", root)
        if glob:
            root = root[:glob.start()].rsplit("/", 1)[0] if "/" in root[:glob.start()] else ""
        roots.append(root)
    return roots


def touches(write: str, u: Unit) -> bool:
    if write == "*":
        return True
    paths = _search_roots(u) if u.kind == "search" else [u.path]
    if write == RAN:
        return any(p.startswith("/") or BUILD_DIRS & set(p.split("/")) for p in paths)
    return any(_under(p, write) or (u.kind == "search" and _under(write, p)) for p in paths)


def call_kind(name: str, io, command: str) -> str:
    if name in EDIT_TOOLS or any(not w.startswith("/") for w in io.writes) or io.unknown_write:
        return "edit"
    if io.units:
        return "read"
    if name == "list_dir":
        return "list"
    if name == "run_command":
        if any(w in command for w in TEST_WORDS):
            return "test_or_run"
        return "list" if re.search(r"(?:^|&&|;|\|)\s*(?:ls|find|tree)\b", command) else "other"
    return "other"


def view_states(view: list[dict]) -> dict[str, str]:
    states = {}
    for msg in view:
        if msg.get("role") == "tool":
            content = msg.get("content")
            text = content if isinstance(content, str) else json.dumps(content)
            states[msg.get("tool_call_id")] = "elided" if text.startswith(ELIDED) else "raw"
    return states


def analyze_run(spec: dict) -> dict:
    run_dir = Path(spec["run_dir"])
    solved, status = outcome(spec)
    row = dict(spec, solved=solved, status=status)
    if status.startswith("excluded"):
        return dict(run=row, calls=[])
    events = read_events(run_dir)
    results = {}
    for e in events:
        if e["event_type"] == "tool.result":
            results[e["tool_call_id"]] = e
    prepared: dict[int, dict] = {}
    calls = []
    model_calls = 0
    for e in events:
        kind = e["event_type"]
        if kind == "model.started":
            model_calls += 1
        elif kind == "context.prepared":
            step = step_number(e)
            prepared[step if step is not None else payload(run_dir, e)["step"]] = e
        elif kind == "tool.intent":
            p = payload(run_dir, e)
            res = results.get(e["tool_call_id"])
            rp = payload(run_dir, res) if res else {}
            args = p.get("arguments") or {}
            output = rp.get("output") if isinstance(rp.get("output"), str) else None
            io = call_io(p["name"], args, output, bool(rp.get("success")))
            command = args.get("command") if isinstance(args.get("command"), str) else ""
            calls.append(dict(index=len(calls), step=step_number(e), call_id=e["tool_call_id"], name=p["name"],
                              args=args, io=io, kind=call_kind(p["name"], io, command),
                              view_event=prepared.get(step_number(e))))

    view_cache: dict[int, dict] = {}

    def view_of(call) -> dict | None:
        ev = call["view_event"]
        if ev is None:
            return None
        if call["step"] not in view_cache:
            view_cache[call["step"]] = view_states(payload(run_dir, ev)["view"])
        return view_cache[call["step"]]

    lengths: dict[str, int] = {}
    reads: list[tuple[int, int, Unit, str]] = []  # (call index, step, unit, call_id)
    writes: list[tuple[int, str]] = []  # (call index, path or "*")
    out_calls = []
    for c in calls:
        io = c["io"]
        lengths.update(io.file_lengths)
        repeated, after_write, cover, prior_ids, gaps = [], False, [], set(), []
        for u in io.units:
            overlapping = [(i, s, p, cid) for i, s, p, cid in reads if s < c["step"] and overlaps(u, p, lengths)]
            fresh = [(i, s, p, cid) for i, s, p, cid in overlapping
                     if not any(i < wi < c["index"] and touches(w, u) for wi, w in writes)]
            fresh_cover = coverage(u, [p for _, _, p, _ in fresh], lengths)
            if fresh_cover >= MIN_OVERLAP:
                repeated.append((u, [(p, cid) for _, _, p, cid in fresh]))
                prior_ids.update(cid for _, _, _, cid in fresh)
                cover.append(fresh_cover)
                substantial = [i for i, _, p, _ in fresh if coverage(u, [p], lengths) >= MIN_OVERLAP]
                gaps.append(c["index"] - max(substantial or [i for i, _, _, _ in fresh]))
            elif coverage(u, [p for _, _, p, _ in overlapping], lengths) >= MIN_OVERLAP:
                after_write = True
        repeated_units = len(repeated)
        rec = dict(index=c["index"], step=c["step"], call_id=c["call_id"], name=c["name"], kind=c["kind"],
                   units=[u.__dict__ for u in io.units], unparsed=io.unparsed,
                   reread=repeated_units > 0,
                   covered=bool(io.units) and repeated_units == len(io.units) and all(x >= COVER for x in cover),
                   reread_after_write=after_write and repeated_units == 0,
                   source=("search" if io.units and all(u.kind == "search" for u in io.units)
                           else io.units[0].source if io.units else None))
        if c["name"] == "run_command":
            rec["command"] = c["args"].get("command")
        elif c["name"] in ("read_file", "search_code"):
            rec["args"] = c["args"]
        if io.writes or io.unknown_write:
            rec["writes"] = sorted(io.writes) + (["*"] if io.unknown_write else [])
        if io.ran:
            rec["ran"] = True
        if rec["reread"]:
            states = view_of(c)
            rec["prior_call_ids"] = sorted(prior_ids)
            rec["gap"] = min(gaps)
            if states is None:
                rec["view_state"] = "no_view"
            else:
                unit_states = []
                for u, priors in repeated:
                    raw_cover = coverage(u, [p for p, cid in priors if states.get(cid) == "raw"], lengths)
                    if raw_cover >= COVER:
                        unit_states.append("raw")
                    elif raw_cover >= MIN_OVERLAP:
                        unit_states.append("partial")
                    elif any(states.get(cid) == "elided" for _, cid in priors):
                        unit_states.append("elided")
                    else:
                        unit_states.append("absent")
                rec["view_state"] = ("raw" if all(s == "raw" for s in unit_states)
                                     else "partial" if {"raw", "partial"} & set(unit_states)
                                     else "elided" if "elided" in unit_states else "absent")
                rec["prior_states"] = {cid: states.get(cid, "absent") for cid in sorted(prior_ids)}
            rec["masking_started"] = states is not None and "elided" in states.values()
        for u in io.units:
            reads.append((c["index"], c["step"], u, c["call_id"]))
        for w in io.writes:
            writes.append((c["index"], w))
        if io.unknown_write:
            writes.append((c["index"], "*"))
        if io.ran:
            writes.append((c["index"], RAN))
        out_calls.append(rec)

    final = None
    for step in sorted(prepared, reverse=True):
        final = payload(run_dir, prepared[step])
        break
    first_masked = None
    for step in sorted(prepared):
        masking = (payload(run_dir, prepared[step]).get("stats") or {}).get("masking") or {}
        if masking.get("compacted_tool_count"):
            first_masked = step
            break
    final_states = view_states(final["view"]) if final else {}
    names = {c["call_id"]: c["name"] for c in calls}
    elided_by_tool = Counter(names.get(cid) for cid, s in final_states.items() if s == "elided")
    masking = ((final or {}).get("stats") or {}).get("masking") or {}
    for rec in out_calls:
        rec["early"] = rec["step"] < model_calls / 2
        rec["after_first_mask"] = first_masked is not None and rec["step"] >= first_masked
    row.update(model_calls=model_calls, tool_calls=len(out_calls),
               read_calls=sum(1 for r in out_calls if r["units"]),
               reread_calls=sum(r["reread"] for r in out_calls),
               covered_calls=sum(r["covered"] for r in out_calls),
               reread_after_write_calls=sum(r["reread_after_write"] for r in out_calls),
               unparsed_commands=sum(r["unparsed"] for r in out_calls),
               first_masked_step=first_masked, keep_recent=masking.get("keep_recent"),
               final_view_elided_by_tool=dict(elided_by_tool),
               final_view_tool_messages=len(final_states))
    return dict(run=row, calls=out_calls)


# --- aggregation -----------------------------------------------------------------------------------------------

def pct(a: int, b: int) -> float | None:
    return round(100 * a / b, 1) if b else None


def median(values: list[float]) -> float | None:
    if not values:
        return None
    s = sorted(values)
    mid = len(s) // 2
    return s[mid] if len(s) % 2 else (s[mid - 1] + s[mid]) / 2


def group_table(runs: list[dict], calls_by_run: dict[str, list[dict]]) -> dict:
    tool = sum(r["tool_calls"] for r in runs)
    read = sum(r["read_calls"] for r in runs)
    rr = [c for r in runs for c in calls_by_run[r["run_dir"]] if c["reread"]]
    cov = sum(r["covered_calls"] for r in runs)
    states = Counter(c["view_state"] for c in rr)
    by_source = defaultdict(Counter)
    for c in rr:
        by_source[c["source"]][c["view_state"]] += 1
    reads_by_source = Counter(c["source"] for r in runs for c in calls_by_run[r["run_dir"]] if c["units"])
    position = Counter(("early" if c["early"] else "late") for c in rr)
    mask_pos = Counter(("after_first_mask" if c["after_first_mask"] else "before_first_mask") for c in rr)
    late_state = Counter(c["view_state"] for c in rr if c["after_first_mask"])
    per_run = [r["reread_calls"] / r["tool_calls"] for r in runs if r["tool_calls"]]
    masked = states["elided"] + states["absent"]
    gaps = sorted(c["gap"] for c in rr)
    return dict(
        runs=len(runs), tool_calls=tool, read_calls=read, reread_calls=len(rr), covered_calls=cov,
        reread_after_write_calls=sum(r["reread_after_write_calls"] for r in runs),
        unparsed_commands=sum(r["unparsed_commands"] for r in runs),
        reread_pct_of_tool_calls=pct(len(rr), tool), reread_pct_of_read_calls=pct(len(rr), read),
        covered_pct_of_tool_calls=pct(cov, tool),
        masked_reread_pct_of_tool_calls=pct(masked, tool),
        masked_or_partial_reread_pct_of_tool_calls=pct(masked + states["partial"], tool),
        mean_run_reread_pct=round(100 * sum(per_run) / len(per_run), 1) if per_run else None,
        gap_to_latest_prior=dict(
            median=median(gaps), p75=gaps[int(0.75 * (len(gaps) - 1))] if gaps else None,
            **{f"le_{k}_pct": pct(sum(g <= k for g in gaps), len(gaps)) for k in (4, 8, 16)},
            histogram={str(k): sum(g == k for g in gaps) for k in range(1, 17)} | {">16": sum(g > 16 for g in gaps)}),
        view_state=dict(states), view_state_pct={k: pct(v, len(rr)) for k, v in states.items()},
        view_state_after_first_mask=dict(late_state),
        by_source={k: dict(v) for k, v in sorted(by_source.items(), key=lambda kv: str(kv[0]))},
        read_calls_by_source=dict(reads_by_source),
        position=dict(position), mask_position=dict(mask_pos),
        runs_with_masking=sum(r["first_masked_step"] is not None for r in runs),
        median_first_masked_step=sorted(r["first_masked_step"] for r in runs if r["first_masked_step"] is not None)[
            sum(r["first_masked_step"] is not None for r in runs) // 2] if any(r["first_masked_step"] is not None for r in runs) else None,
        read_file_elided_in_final_view_runs=sum(bool(r["final_view_elided_by_tool"].get("read_file")) for r in runs),
    )


FIRST_CALLS = 15


def solved_relation(runs: list[dict], calls_by_run: dict[str, list[dict]] | None = None) -> dict:
    """Per task: mean re-read share of solved minus unsolved runs.

    Share = re-read calls / tool calls over the whole run; with calls_by_run, over the first FIRST_CALLS tool
    calls only, for runs that made at least that many (removes the length effect: unsolved runs run longer).
    """
    by_task = defaultdict(lambda: {True: [], False: []})
    for r in runs:
        if not r["tool_calls"] or r["solved"] is None:
            continue
        if calls_by_run is None:
            by_task[r["task"]][r["solved"]].append(r["reread_calls"] / r["tool_calls"])
        elif r["tool_calls"] >= FIRST_CALLS:
            head = calls_by_run[r["run_dir"]][:FIRST_CALLS]
            by_task[r["task"]][r["solved"]].append(sum(c["reread"] for c in head) / FIRST_CALLS)
    diffs = {}
    for task, g in sorted(by_task.items()):
        if g[True] and g[False]:
            diffs[task] = dict(n_solved=len(g[True]), n_unsolved=len(g[False]),
                               solved=round(100 * sum(g[True]) / len(g[True]), 1),
                               unsolved=round(100 * sum(g[False]) / len(g[False]), 1))
            diffs[task]["diff"] = round(diffs[task]["solved"] - diffs[task]["unsolved"], 1)
    values = [d["diff"] for d in diffs.values()]
    return dict(tasks_total=len(by_task), tasks_mixed=len(diffs),
                tasks_all_solved=sum(1 for g in by_task.values() if g[True] and not g[False]),
                tasks_none_solved=sum(1 for g in by_task.values() if g[False] and not g[True]),
                mean_diff_pp=round(sum(values) / len(values), 1) if values else None,
                tasks_solved_lower=sum(v < 0 for v in values), tasks_solved_higher=sum(v > 0 for v in values),
                per_task=diffs)


def analyze_all(workers: int, limit: int | None) -> None:
    specs = discover()
    if limit:
        seen = Counter()
        specs = [s for s in specs if seen.update([s["experiment"]]) or seen[s["experiment"]] <= limit]
    print("runs discovered", Counter(s["experiment"] for s in specs), flush=True)
    results = []
    with ProcessPoolExecutor(workers) as pool:
        for i, res in enumerate(pool.map(analyze_run, specs, chunksize=4)):
            results.append(res)
            if (i + 1) % 100 == 0:
                print("analyzed", i + 1, flush=True)
    CALLS_OUT.parent.mkdir(parents=True, exist_ok=True)
    with CALLS_OUT.open("w", encoding="utf-8") as fh:
        for res in results:
            for c in res["calls"]:
                fh.write(json.dumps(dict(run_dir=res["run"]["run_dir"].replace("\\", "/"),
                                         experiment=res["run"]["experiment"], config=res["run"]["config"], **c),
                                    ensure_ascii=False) + "\n")
    runs = [res["run"] for res in results]
    for r in runs:
        r["run_dir"] = r["run_dir"].replace("\\", "/")
    write_json("reread_runs.json", runs)


def summarize() -> None:
    runs = load_json(OUT_DIR / "reread_runs.json")
    calls_by_run = defaultdict(list)
    with CALLS_OUT.open(encoding="utf-8") as fh:
        for line in fh:
            c = json.loads(line)
            calls_by_run[c["run_dir"].replace("\\", "/")].append(c)
    kept = [r for r in runs if not r["status"].startswith("excluded")]
    excluded = Counter((r["experiment"], r["status"]) for r in runs if r["status"].startswith("excluded"))
    groups = defaultdict(list)
    for r in kept:
        groups[(r["experiment"], r["config"])].append(r)
        groups[(r["experiment"], "all")].append(r)
    summary = dict(
        schema="reread-analysis.v1",
        definitions=__doc__.split("Definitions (see reads.py for what counts as a read unit):")[1].strip(),
        coverage_threshold=COVER,
        excluded={f"{e} {s}": n for (e, s), n in sorted(excluded.items())},
        groups={f"{e} {c}": group_table(rs, calls_by_run) for (e, c), rs in sorted(groups.items())},
        solved_relation={f"{e} {c}": solved_relation(rs) for (e, c), rs in sorted(groups.items())
                         if e not in ("P4-first",)},
        solved_relation_first_calls={f"{e} {c}": solved_relation(rs, calls_by_run)
                                     for (e, c), rs in sorted(groups.items()) if e not in ("P4-first",)},
        first_calls=FIRST_CALLS,
        tool_calls_by_outcome={f"{e} {c}": {
            "solved_median": median([r["tool_calls"] for r in rs if r["solved"]]),
            "unsolved_median": median([r["tool_calls"] for r in rs if r["solved"] is False])}
            for (e, c), rs in sorted(groups.items()) if e not in ("P4-first",)},
        top_runs=[dict(run_dir=r["run_dir"], experiment=r["experiment"], config=r["config"],
                       reread_calls=r["reread_calls"], tool_calls=r["tool_calls"], solved=r["solved"])
                  for r in sorted(kept, key=lambda r: -r["reread_calls"])[:10]],
    )
    path = write_json("reread_summary.json", summary)
    for name, g in summary["groups"].items():
        print(name, {k: g[k] for k in ("runs", "tool_calls", "reread_calls", "reread_pct_of_tool_calls",
                                        "covered_pct_of_tool_calls", "masked_reread_pct_of_tool_calls",
                                        "view_state_pct")})
    print("wrote", path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=6)
    parser.add_argument("--limit", type=int, help="first N runs per experiment (smoke test)")
    parser.add_argument("--summary-only", action="store_true",
                        help="rebuild reread_summary.json from reread_runs.json and the per-call file")
    args = parser.parse_args()
    if not args.summary_only:
        analyze_all(args.workers, args.limit)
    summarize()


if __name__ == "__main__":
    main()
