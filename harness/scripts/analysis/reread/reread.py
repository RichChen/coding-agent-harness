"""Re-reads in A5, A6-R, CR-2 and P4 runs, and whether the earlier result was still verbatim in the model's view.

Read-only: journals under runs/ and D:/crq/artifacts are opened read-only (sqlite immutable); no model calls,
no Docker. Writes out/reread_runs.json (one row per run), out/reread_summary.json (tables) and the per-call
detail .tmp/reread/calls.jsonl (not committed; regenerated by this script).

Definitions (see reads.py for what counts as a read unit):
- A read call is a tool call with at least one read unit.
- A read unit is repeated when earlier read units, issued at earlier model steps (calls in the same step were
  proposed together and could not see each other's results), already cover at least 20% of it: same file and
  overlapping line ranges, or the same search pattern on the same paths; counting only earlier reads that no
  write touched in between (a write to a file, to a directory above it, or under the searched paths; a command
  that ran code touches files outside the workspace and under build/output directories). Reads that reach 20%
  only with earlier reads invalidated by a write are counted separately as reread_after_write and are not
  re-reads. The 20% floor keeps sequential paging (next page starting at the previous page's last line) out.
- A re-read call has at least one repeated unit. Covered re-read: every unit of the call is repeated and at
  least 80% of each line range was already read (whole-file reads need a known file length).
- View state of a re-read: the view sent to the model at that step (context.prepared) is searched for the tool
  messages of the earlier calls counted above. Per repeated unit: raw = the earlier results still verbatim in
  the view cover at least 80% of it; partial = they cover 20-80%; elided = less than 20% verbatim and at least
  one "[Elided result of ...]" placeholder; absent = otherwise (the earlier tool messages are gone from the
  view). A call is raw if all its repeated units are raw, partial if any unit is raw or partial, otherwise
  elided or absent.
- Position: early if step < model_calls / 2. Masking started: the view at that step already holds a placeholder.
- Gap: tool calls between a re-read and the latest earlier call that alone covers at least 20% of a repeated
  unit (1 = the previous call; smallest over the repeated units). Micro-compact
  keeps the latest keep_recent=4 tool results verbatim, so a gap above about 4 means the earlier result was
  normally elided by then.
"""

